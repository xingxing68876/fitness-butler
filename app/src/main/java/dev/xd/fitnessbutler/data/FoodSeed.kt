    /** 按分类过滤 */
    fun byCategory(cat: String): List<Food> =
        if (cat == "全部" || cat.isEmpty()) ALL else ALL.filter { it.category == cat }

    /** 按关键字搜索菜名 */
    fun search(q: String): List<Food> =
        if (q.isBlank()) ALL else ALL.filter { it.name.contains(q.trim()) }

    /** 菜名精确/模糊命中,取第一条 */
